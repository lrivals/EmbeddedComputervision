"""python -m tools.figures <nom|famille|all> … ; --list ; --run KIND --dir PATH (mode auto)."""

import argparse
import os
import sys
from pathlib import Path

from tools.figures import BUILD, FIGURES, RESULTS, _rel, out_dir_of, run, select

FAMILY_TITLES = {"resultats": "Results (D)", "modeles": "Models (B)",
                 "projet": "Project development (E)", "materiel": "Hardware (C)",
                 "maths": "Reimplementation from scratch (F)", "reseaux": "Networks in detail (G)"}


def images_of(fig, results=RESULTS, build=BUILD):
    d = out_dir_of(fig, results, build)
    return sorted(set(d.glob(f"{fig.name}.png")) | set(d.glob(f"{fig.name}_*.png")))


def gallery(status=None, results=RESULTS, build=BUILD):
    """Réécrit `results/figures.md` (à côté de `results/figures/`) depuis le registre."""
    status = status or {}
    path = Path(results).parent / "figures.md"
    lines = ["# Figures (M13)", "",
             "Gallery generated by `python -m tools.figures all` (`make figures`) from the "
             "registry of `tools/figures/`; do not edit by hand. Each figure is "
             "regenerated by its command and reads its data in the source given. The "
             "missing figures wait for their data (see the command of the task).", ""]
    lead = FIGURES.get("chaine_verif")
    if lead and images_of(lead, results, build):
        rel = os.path.relpath(images_of(lead, results, build)[0], path.parent)
        lines += ["## In short: the verification chain", "", lead.caption, "",
                  f"![chaine_verif]({rel})", ""]
    for fam, title in FAMILY_TITLES.items():
        figs = [f for f in FIGURES.values() if f.family == fam]
        if not figs:
            continue
        lines += [f"## {title}", ""]
        for f in figs:
            lines += [f"### {f.task} — `{f.name}`", "", f.caption, "",
                      f"- Commande : `{f.command}`", f"- Source : `{f.source}`"]
            imgs = images_of(f, results, build)
            if f.subset:
                where = _rel(out_dir_of(f, results, build))
                lines.append(f"- Subset of images: output in `{where}/`, not published "
                             "in `results/` (M12 rule).")
            elif imgs:
                lines.append("")
                for p in imgs:
                    rel = os.path.relpath(p, path.parent)
                    lines.append(f"![{p.stem}]({rel})")
            else:
                why = status.get(f.name, ("", "not generated yet"))[1]
                lines.append(f"- Not generated: {why}.")
            lines.append("")
    path.write_text("\n".join(lines))
    return path


def main(argv=None):
    ap = argparse.ArgumentParser(prog="python -m tools.figures", description=__doc__)
    ap.add_argument("targets", nargs="*", default=[], help="name, family or all")
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--results", type=Path, default=RESULTS)
    ap.add_argument("--build", type=Path, default=BUILD)
    ap.add_argument("--no-gallery", action="store_true")
    ap.add_argument("--run", default=None, help="auto mode: run type (train, eval-quant…)")
    ap.add_argument("--dir", type=Path, default=None, help="auto mode: outputs of the run")
    args = ap.parse_args(argv)

    if args.list:
        for f in FIGURES.values():
            print(f"{f.name:20s} {f.family:10s} {f.task:7s} {f.source}")
        return 0
    if args.run:
        from tools.figures.auto import after_run

        after_run(args.run, args.dir or Path.cwd())
        return 0
    if not args.targets:
        ap.error("give a figure, a family or all (see --list)")
    status = run(select(args.targets), args.results, args.build)
    if "all" in args.targets and not args.no_gallery:
        print(f"→ {gallery(status, args.results, args.build)}")
    n_ok = sum(s == "ok" for s, _ in status.values())
    print(f"{n_ok} generated, {len(status) - n_ok} skipped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
